-- ---------------------------------------------------------------------------
-- updated_at triggers
-- ---------------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array['users','user_profiles','linked_discord_accounts','retailers',
                     'stores','products','product_identifiers','inventory',
                     'watchlists','notification_preferences'] loop
    execute format('drop trigger if exists trg_%s_updated_at on public.%s', t, t);
    execute format('create trigger trg_%s_updated_at before update on public.%s
                    for each row execute function public.set_updated_at()', t, t);
  end loop;
end $$;

-- ---------------------------------------------------------------------------
-- Row Level Security — users only see their own rows.
-- Enable RLS on user-owned tables. Public catalog tables
-- (retailers, products, product_identifiers, stores, inventory_sources)
-- are readable by everyone; inventory is readable by everyone because it
-- is store-level verified stock, not private user data.
-- In Supabase, the app must use auth.uid() mapped to users.auth_user_id.
-- The policies below use a helper: the signed-in user's app id is resolved
-- via users.auth_user_id = auth.uid(). If you use Supabase Auth directly,
-- replace the subquery with auth.uid() = user_id where user_id is the
-- auth id. See README.md for the exact mapping.
-- ---------------------------------------------------------------------------
alter table public.users enable row level security;
alter table public.user_profiles enable row level security;
alter table public.linked_discord_accounts enable row level security;
alter table public.watchlists enable row level security;
alter table public.stock_alerts enable row level security;
alter table public.notification_preferences enable row level security;
alter table public.notifications enable row level security;
alter table public.search_history enable row level security;
alter table public.retailers enable row level security;
alter table public.stores enable row level security;
alter table public.products enable row level security;
alter table public.product_identifiers enable row level security;
alter table public.inventory enable row level security;
alter table public.inventory_history enable row level security;
alter table public.inventory_sources enable row level security;

-- Catalog: public read, no public write (writes only via service role).
create policy "catalog read" on public.retailers for select using (true);
create policy "catalog read" on public.stores for select using (true);
create policy "catalog read" on public.products for select using (true);
create policy "catalog read" on public.product_identifiers for select using (true);
create policy "catalog read" on public.inventory_sources for select using (true);
create policy "inventory read" on public.inventory for select using (true);
create policy "inventory history read" on public.inventory_history for select using (true);

-- User-owned: a user can only select/insert/update/delete their own rows.
-- These policies assume public.users.auth_user_id = auth.uid().
-- Service-role / server-side sync jobs bypass RLS and write inventory.
create policy "own users row" on public.users
  for all using (auth_user_id = auth.uid()) with check (auth_user_id = auth.uid());

create policy "own profile" on public.user_profiles
  for all using (user_id in (select id from public.users where auth_user_id = auth.uid()))
  with check (user_id in (select id from public.users where auth_user_id = auth.uid()));

create policy "own discord link" on public.linked_discord_accounts
  for all using (user_id in (select id from public.users where auth_user_id = auth.uid()))
  with check (user_id in (select id from public.users where auth_user_id = auth.uid()));

create policy "own watchlist" on public.watchlists
  for all using (user_id in (select id from public.users where auth_user_id = auth.uid()))
  with check (user_id in (select id from public.users where auth_user_id = auth.uid()));

create policy "own stock alerts" on public.stock_alerts
  for select using (user_id in (select id from public.users where auth_user_id = auth.uid()));

create policy "own notification prefs" on public.notification_preferences
  for all using (user_id in (select id from public.users where auth_user_id = auth.uid()))
  with check (user_id in (select id from public.users where auth_user_id = auth.uid()));

create policy "own notifications" on public.notifications
  for all using (user_id in (select id from public.users where auth_user_id = auth.uid()))
  with check (user_id in (select id from public.users where auth_user_id = auth.uid()));

create policy "own search history" on public.search_history
  for all using (user_id in (select id from public.users where auth_user_id = auth.uid()))
  with check (user_id in (select id from public.users where auth_user_id = auth.uid()));

