-- Pokémon TCG Local Stock Tracker — Supabase / Postgres schema
-- Source of truth: the tracker artifact's project pack (getprojectpack).
-- Run in Supabase SQL Editor, or:  psql "$DATABASE_URL" -f supabase/schema.sql
--
-- RULES (do not weaken these):
--  * Never invent inventory quantities. inventory starts EMPTY — no seed rows.
--  * Never treat a product listing as store availability.
--  * Never show Unknown as In stock. Availability is one of:
--    in_stock / limited_stock / out_of_stock / unknown / last_known_in_stock
--  * Checks older than 24h are demoted to last_known_in_stock by the app,
--    never silently shown as current.
--  * Users only see their own rows on user-owned tables (RLS below).
--  * No real API keys, tokens, or secrets are stored in this repo.

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- Helper: updated_at
-- ---------------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- 1. users — mirrors Supabase Auth (auth.users). One row per app user.
--    In Supabase, create this row from auth.users via trigger, or let the app
--    upsert it on first sign-in. Never store passwords here.
-- ---------------------------------------------------------------------------
create table if not exists public.users (
  id uuid primary key default gen_random_uuid(),
  auth_user_id uuid unique, -- auth.users.id when using Supabase Auth
  email text unique not null,
  display_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_users_email on public.users (email);
create index if not exists idx_users_auth_user_id on public.users (auth_user_id);

-- ---------------------------------------------------------------------------
-- 2. user_profiles — one per user, extra profile/settings fields
-- ---------------------------------------------------------------------------
create table if not exists public.user_profiles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references public.users (id) on delete cascade,
  display_name text,
  default_zip text check (default_zip ~ '^[0-9]{5}$'),
  default_radius_miles integer not null default 25 check (default_radius_miles in (5, 10, 25, 50, 100)),
  timezone text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_user_profiles_user_id on public.user_profiles (user_id);

-- ---------------------------------------------------------------------------
-- 3. linked_discord_accounts — Discord OAuth linking (scopes: identify)
--    One Discord account per user. The bot binds via a one-time link code
--    generated by the website; the website never stores the bot token.
-- ---------------------------------------------------------------------------
create table if not exists public.linked_discord_accounts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.users (id) on delete cascade,
  discord_user_id text not null,
  discord_username text,
  linked_at timestamptz not null default now(),
  unlinked_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, discord_user_id),
  unique (discord_user_id)
);
create index if not exists idx_linked_discord_user_id on public.linked_discord_accounts (user_id);
create index if not exists idx_linked_discord_discord_id on public.linked_discord_accounts (discord_user_id);

-- ---------------------------------------------------------------------------
-- 4. retailers — the 8-retailer registry (seeded below)
-- ---------------------------------------------------------------------------
create table if not exists public.retailers (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique, -- e.g. 'best-buy'
  name text not null,        -- e.g. 'Best Buy'
  website_url text,
  integration_status text not null default 'unsupported'
    check (integration_status in ('live', 'awaiting_credentials', 'unsupported')),
  integration_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_retailers_slug on public.retailers (slug);

-- ---------------------------------------------------------------------------
-- 5. stores — physical store locations (from retailer store-locator APIs
--    and OpenStreetMap geocoding). A store row is a location, NOT proof of
--    stock — stock lives only in inventory.
-- ---------------------------------------------------------------------------
create table if not exists public.stores (
  id uuid primary key default gen_random_uuid(),
  retailer_id uuid not null references public.retailers (id) on delete restrict,
  external_store_id text, -- retailer store id, when the retailer provides one
  name text not null,
  address text,
  city text,
  state text,
  zip text check (zip is null or zip ~ '^[0-9]{5}$'),
  latitude double precision,
  longitude double precision,
  phone text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (retailer_id, external_store_id)
);
create index if not exists idx_stores_retailer_id on public.stores (retailer_id);
create index if not exists idx_stores_zip on public.stores (zip);
create index if not exists idx_stores_lat_lon on public.stores (latitude, longitude);

-- ---------------------------------------------------------------------------
-- 6. products — the tracking catalog (20 real sealed products seeded below).
--    No invented SKUs: sku / upc are nullable and only filled from a
--    verified source (retailer API or TCGdex).
-- ---------------------------------------------------------------------------
create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null, -- e.g. 'Pokémon TCG: Mega Evolution Elite Trainer Box'
  set_name text,
  category text not null check (category in (
    'Elite Trainer Box', 'Booster Box', 'Booster Bundle', 'Booster Pack',
    'Collection Box', 'Special Collection', 'Tin', 'Premium Collection',
    'Accessory'
  )),
  image_url text,
  tcgdex_set_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_products_name on public.products (name);
create index if not exists idx_products_category on public.products (category);
create index if not exists idx_products_set_name on public.products (set_name);

-- ---------------------------------------------------------------------------
-- 7. product_identifiers — SKUs / UPCs / TCINs per retailer, when verified
-- ---------------------------------------------------------------------------
create table if not exists public.product_identifiers (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products (id) on delete cascade,
  retailer_id uuid references public.retailers (id) on delete set null,
  identifier_type text not null check (identifier_type in ('sku', 'upc', 'tcin', 'asin', 'other')),
  identifier_value text not null,
  source text, -- e.g. 'best_buy_api', 'tcgdex'
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (product_id, retailer_id, identifier_type, identifier_value)
);
create index if not exists idx_product_identifiers_product_id on public.product_identifiers (product_id);
create index if not exists idx_product_identifiers_value on public.product_identifiers (identifier_value);

-- ---------------------------------------------------------------------------
-- 8. inventory — ONE row per (product, store), latest verified state only.
--    Starts EMPTY. A row is created only by a verified retailer check.
--    quantity is NULL unless the source returned a number.
-- ---------------------------------------------------------------------------
create table if not exists public.inventory (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products (id) on delete cascade,
  store_id uuid not null references public.stores (id) on delete cascade,
  retailer_id uuid not null references public.retailers (id) on delete restrict,
  availability text not null default 'unknown'
    check (availability in ('in_stock', 'limited_stock', 'out_of_stock', 'unknown', 'last_known_in_stock')),
  quantity integer check (quantity is null or quantity >= 0),
  price_cents integer check (price_cents is null or price_cents >= 0),
  fulfillment_type text check (fulfillment_type is null or fulfillment_type in ('in_store', 'pickup', 'shipping', 'ship_to_store')),
  source_id uuid references public.inventory_sources (id) on delete set null,
  last_checked_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (product_id, store_id)
);
create index if not exists idx_inventory_product_id on public.inventory (product_id);
create index if not exists idx_inventory_store_id on public.inventory (store_id);
create index if not exists idx_inventory_availability on public.inventory (availability);
create index if not exists idx_inventory_last_checked on public.inventory (last_checked_at);

-- ---------------------------------------------------------------------------
-- 9. inventory_history — every check, append-only. Powers freshness,
--    "last known in stock", and alert deduplication.
-- ---------------------------------------------------------------------------
create table if not exists public.inventory_history (
  id uuid primary key default gen_random_uuid(),
  inventory_id uuid references public.inventory (id) on delete set null,
  product_id uuid not null references public.products (id) on delete cascade,
  store_id uuid not null references public.stores (id) on delete cascade,
  retailer_id uuid not null references public.retailers (id) on delete restrict,
  availability text not null
    check (availability in ('in_stock', 'limited_stock', 'out_of_stock', 'unknown', 'last_known_in_stock')),
  quantity integer check (quantity is null or quantity >= 0),
  price_cents integer check (price_cents is null or price_cents >= 0),
  source_id uuid references public.inventory_sources (id) on delete set null,
  checked_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);
create index if not exists idx_inventory_history_product_store on public.inventory_history (product_id, store_id);
create index if not exists idx_inventory_history_checked_at on public.inventory_history (checked_at);

-- ---------------------------------------------------------------------------
-- 10. watchlists — one row per (user, product). Alert settings live here.
-- ---------------------------------------------------------------------------
create table if not exists public.watchlists (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.users (id) on delete cascade,
  product_id uuid not null references public.products (id) on delete cascade,
  zip text check (zip is null or zip ~ '^[0-9]{5}$'),
  radius_miles integer not null default 25 check (radius_miles in (5, 10, 25, 50, 100)),
  retailer_ids uuid[] not null default '{}',
  notify_website boolean not null default true,
  notify_discord boolean not null default false,
  notify_email boolean not null default false,
  cooldown_minutes integer not null default 60 check (cooldown_minutes >= 0),
  last_notified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, product_id)
);
create index if not exists idx_watchlists_user_id on public.watchlists (user_id);
create index if not exists idx_watchlists_product_id on public.watchlists (product_id);

-- ---------------------------------------------------------------------------
-- 11. stock_alerts — deduped alert records. One alert per
--     (watchlist, product, store, availability-transition) per cooldown.
-- ---------------------------------------------------------------------------
create table if not exists public.stock_alerts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.users (id) on delete cascade,
  watchlist_id uuid references public.watchlists (id) on delete set null,
  product_id uuid not null references public.products (id) on delete cascade,
  store_id uuid references public.stores (id) on delete set null,
  previous_availability text,
  new_availability text not null
    check (new_availability in ('in_stock', 'limited_stock', 'out_of_stock', 'unknown', 'last_known_in_stock')),
  channel text not null check (channel in ('website', 'discord', 'email')),
  sent_at timestamptz not null default now(),
  dedupe_key text unique,
  created_at timestamptz not null default now()
);
create index if not exists idx_stock_alerts_user_id on public.stock_alerts (user_id);
create index if not exists idx_stock_alerts_sent_at on public.stock_alerts (sent_at);

-- ---------------------------------------------------------------------------
-- 12. notification_preferences — one row per user
-- ---------------------------------------------------------------------------
create table if not exists public.notification_preferences (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references public.users (id) on delete cascade,
  website_enabled boolean not null default true,
  discord_enabled boolean not null default false,
  email_enabled boolean not null default false,
  email_address text,
  default_cooldown_minutes integer not null default 60 check (default_cooldown_minutes >= 0),
  default_radius_miles integer not null default 25 check (default_radius_miles in (5, 10, 25, 50, 100)),
