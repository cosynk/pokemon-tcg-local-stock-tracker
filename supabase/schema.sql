create index if not exists idx_notification_prefs_user_id on public.notification_preferences (user_id);

-- ---------------------------------------------------------------------------
-- 13. notifications — in-app notification history (website channel)
-- ---------------------------------------------------------------------------
create table if not exists public.notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.users (id) on delete cascade,
  type text not null default 'stock_available',
  title text not null,
  body text,
  product_id uuid references public.products (id) on delete set null,
  store_id uuid references public.stores (id) on delete set null,
  channel text not null default 'website' check (channel in ('website', 'discord', 'email')),
